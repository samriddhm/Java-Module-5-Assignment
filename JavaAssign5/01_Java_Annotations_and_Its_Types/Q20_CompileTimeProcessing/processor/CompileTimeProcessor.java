import java.io.IOException;
import java.io.Writer;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Messager;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;

/**
 * Q20: an ANNOTATION PROCESSOR - code that the Java COMPILER (javac) runs
 * while it compiles your program (Pluggable Annotation Processing API, JSR 269).
 *
 * It does three typical jobs:
 *   1. Reports information  (NOTE messages for each @Todo)
 *   2. Validates code       (ERROR if an @Immutable class has a non-final field)
 *   3. Generates new code   (writes GeneratedTodoList.java, which javac then compiles)
 *
 * Use it with:  javac -processor CompileTimeProcessor -cp <processor classes> MyFiles.java
 * (or register it in META-INF/services/javax.annotation.processing.Processor)
 */
@SupportedAnnotationTypes({"Immutable", "Todo"})
public class CompileTimeProcessor extends AbstractProcessor {

    private final List<String> todos = new ArrayList<>();
    private boolean fileGenerated = false;
    private int round = 0;

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        Messager log = processingEnv.getMessager();
        round++;
        log.printMessage(Diagnostic.Kind.NOTE, "[processor] round " + round
                + " - annotations to process: " + annotations);

        // ---- Job 2: validate @Immutable classes ----
        for (Element type : roundEnv.getElementsAnnotatedWith(Immutable.class)) {
            if (type.getKind() != ElementKind.CLASS) {
                log.printMessage(Diagnostic.Kind.ERROR, "@Immutable can only be used on classes", type);
                continue;
            }
            boolean ok = true;
            for (Element member : type.getEnclosedElements()) {
                boolean isField = member.getKind() == ElementKind.FIELD;
                boolean isFinal = member.getModifiers().contains(Modifier.FINAL);
                if (isField && !isFinal) {
                    ok = false;
                    log.printMessage(Diagnostic.Kind.ERROR, "@Immutable class '" + type.getSimpleName()
                            + "' has a non-final field '" + member.getSimpleName() + "'", member);
                }
            }
            if (ok) {
                log.printMessage(Diagnostic.Kind.NOTE, "[processor] @Immutable check passed for "
                        + type.getSimpleName());
            }
        }

        // ---- Job 1: report @Todo items ----
        for (Element e : roundEnv.getElementsAnnotatedWith(Todo.class)) {
            Todo todo = e.getAnnotation(Todo.class);   // works for SOURCE annotations at compile time
            String where = (e.getKind() == ElementKind.METHOD)
                    ? e.getEnclosingElement().getSimpleName() + "." + e.getSimpleName() + "()"
                    : e.getSimpleName().toString();
            log.printMessage(Diagnostic.Kind.NOTE, "[processor] TODO in " + where + ": " + todo.value());
            todos.add(where + " -> " + todo.value());
        }

        // ---- Job 3: generate a new source file (only once) ----
        if (!fileGenerated && !todos.isEmpty()) {
            generateTodoList(log);
            fileGenerated = true;
        }
        return true; // these annotations are "claimed" - no other processor needs them
    }

    private void generateTodoList(Messager log) {
        try {
            JavaFileObject file = processingEnv.getFiler().createSourceFile("GeneratedTodoList");
            try (Writer w = file.openWriter()) {
                w.write("// AUTO-GENERATED by CompileTimeProcessor - do not edit\n");
                w.write("public final class GeneratedTodoList {\n");
                w.write("    private GeneratedTodoList() { }\n");
                w.write("    public static final String[] ITEMS = {\n");
                for (String t : todos) {
                    w.write("        \"" + t.replace("\\", "\\\\").replace("\"", "\\\"") + "\",\n");
                }
                w.write("    };\n");
                w.write("}\n");
            }
            log.printMessage(Diagnostic.Kind.NOTE, "[processor] generated GeneratedTodoList.java with "
                    + todos.size() + " item(s)");
        } catch (IOException ex) {
            log.printMessage(Diagnostic.Kind.ERROR, "could not generate file: " + ex.getMessage());
        }
    }
}
